import {expect,test} from '@playwright/test';
import {readFile} from 'node:fs/promises';
import {encodePng} from '../src/decomposer/image';
import {decodeDecompositionDocument} from '../src/decomposer/codec';

function illustration():Buffer{
  const width=40,height=32,rgba=new Uint8Array(width*height*4);
  for(let y=8;y<24;y++)for(let x=4;x<20;x++)rgba.set([188,52,42,255],(y*width+x)*4);
  for(let y=4;y<28;y++)for(let x=20;x<34;x++)rgba.set([31,108,190,255],(y*width+x)*4);
  return Buffer.from(encodePng({width,height,rgba}));
}

test('first-use walkthrough, Help search, dismissal and restart keep project state',async({page})=>{
  await page.goto('/decomposer.html');
  const tour=page.getByRole('complementary',{name:'Getting started walkthrough'});
  await expect(tour).toBeVisible();
  await expect(tour).toContainText('Import an illustration');
  await expect(page.locator('[data-tour="import"]')).toHaveClass(/walkthrough-target/);
  await tour.getByRole('button',{name:'Next'}).click();
  await expect(tour).toContainText('Review editable regions');
  await expect(page.locator('[data-tour="regions"]')).toHaveClass(/walkthrough-target/);
  await tour.getByRole('button',{name:'Back'}).click();
  await expect(tour).toContainText('Import an illustration');
  await page.getByRole('button',{name:'Help',exact:true}).click();
  const help=page.getByRole('dialog',{name:'Help'});
  await expect(help).toBeVisible();
  await expect(tour).toHaveCount(0);
  await expect(help.getByRole('searchbox',{name:'Search help topics'})).toBeFocused();
  await help.getByRole('searchbox',{name:'Search help topics'}).fill('slider');
  await help.getByRole('button',{name:'Animation-ready preparation'}).click();
  await expect(help.getByRole('article')).toContainText('Fixed follows the parent, Hinge rotates, and Slider moves');
  await page.keyboard.press('Escape');
  await expect(help).toHaveCount(0);
  await expect(page.getByRole('button',{name:'Help',exact:true})).toBeFocused();
  await expect(tour).toBeVisible();
  await tour.getByRole('button',{name:'Skip'}).click();
  await expect(tour).toHaveCount(0);
  expect(await page.evaluate(()=>localStorage.getItem('hyde-decomposer-onboarding-v1'))).toBe('done');
  await page.reload();
  await expect(tour).toHaveCount(0);
  await page.getByRole('button',{name:'Help',exact:true}).click();
  await help.getByRole('button',{name:'Restart walkthrough'}).click();
  await expect(tour).toContainText('Import an illustration');
  for(let step=0;step<5;step++)await tour.getByRole('button',{name:'Next'}).click();
  await expect(tour).toContainText('Save or export');
  await tour.getByRole('button',{name:'Finish'}).click();
  await expect(tour).toHaveCount(0);
  await page.getByLabel('Import images').setInputFiles({name:'help-fixture.png',mimeType:'image/png',buffer:illustration()});
  await expect(page.getByRole('status')).toContainText('Automatic first pass found');
  const beforeDownload=page.waitForEvent('download');
  await page.getByRole('button',{name:'Save source'}).click();
  const before=await decodeDecompositionDocument(new Uint8Array(await readFile((await (await beforeDownload).path())!)));
  await page.getByRole('button',{name:'Help',exact:true}).click();
  await help.getByRole('button',{name:'Restart walkthrough'}).click();
  await tour.getByRole('button',{name:'Close walkthrough'}).click();
  const afterDownload=page.waitForEvent('download');
  await page.getByRole('button',{name:'Save source'}).click();
  const after=await decodeDecompositionDocument(new Uint8Array(await readFile((await (await afterDownload).path())!)));
  expect(after.document.revision).toBe(before.document.revision);
  expect(after.document.regions).toEqual(before.document.regions);
  expect(after.sourceBytes.get(after.document.sources[0].id)).toEqual(before.sourceBytes.get(before.document.sources[0].id));
});

test('control guidance works with pointer, keyboard and touch without leaving the viewport',async({page})=>{
  await page.goto('/decomposer.html');
  await page.getByRole('button',{name:'Skip'}).click();
  const info=page.getByRole('button',{name:'About regions'});
  await info.hover();
  await expect(page.getByRole('tooltip')).toContainText('editable image geometry');
  await info.focus();
  await expect(page.getByRole('tooltip')).toBeVisible();
  await page.keyboard.press('Escape');
  await expect(page.getByRole('tooltip')).toHaveCount(0);
  await info.dispatchEvent('pointerdown',{pointerType:'touch'});
  await expect(page.getByRole('tooltip')).toContainText('editable image geometry');
  await page.getByLabel('Import images').setInputFiles({name:'tooltips.png',mimeType:'image/png',buffer:illustration()});
  await expect(page.getByRole('status')).toContainText('Automatic first pass found');
  const color=page.getByRole('slider',{name:'Color granularity'});
  await color.focus();
  await expect(page.getByRole('tooltip')).toContainText('Lower values separate more similar colors');
  const box=await page.getByRole('tooltip').boundingBox();
  expect(box).toBeTruthy();
  expect(box!.x).toBeGreaterThanOrEqual(0);
  expect(box!.x+box!.width).toBeLessThanOrEqual(page.viewportSize()!.width);
  expect(box!.y).toBeGreaterThanOrEqual(0);
  expect(box!.y+box!.height).toBeLessThanOrEqual(page.viewportSize()!.height);
  expect(await color.getAttribute('aria-description')).toContain('Lower values');
  await page.setViewportSize({width:360,height:640});
  await info.hover();
  const narrowBox=await page.getByRole('tooltip').boundingBox();
  expect(narrowBox).toBeTruthy();
  expect(narrowBox!.x).toBeGreaterThanOrEqual(0);
  expect(narrowBox!.x+narrowBox!.width).toBeLessThanOrEqual(360);
  expect(narrowBox!.y).toBeGreaterThanOrEqual(0);
  expect(narrowBox!.y+narrowBox!.height).toBeLessThanOrEqual(640);
});

