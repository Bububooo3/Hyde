import {expect,test} from '@playwright/test';

test('assembly animation clips can be saved, placed, and reopened in a project',async({page})=>{
  await page.goto('/');
  await page.getByRole('button',{name:'New project'}).click();
  await page.getByRole('button',{name:'Done'}).click();
  await page.getByRole('button',{name:'Add rectangle'}).first().click();
  await page.keyboard.press('Control+g');
  await expect(page.locator('.assembly-clips-panel')).toBeVisible();
  await page.getByRole('textbox',{name:'Assembly clip name'}).fill('Turn and reveal');
  await page.getByRole('spinbutton',{name:'Assembly clip length in seconds'}).fill('2');
  await page.getByRole('button',{name:'Save animation clip'}).click();
  await expect(page.locator('.assembly-clip-entry').filter({hasText:'Turn and reveal'})).toHaveCount(1);
  await page.getByRole('button',{name:'Place Turn and reveal clip'}).click();
  const placement=page.locator('.assembly-instance-block');
  await expect(placement).toContainText('Turn and reveal');
  await placement.scrollIntoViewIfNeeded();
  const initial=await placement.boundingBox();expect(initial).toBeTruthy();
  const centerY=initial!.y+initial!.height/2;
  await page.mouse.move(initial!.x+initial!.width/2,centerY);
  await page.mouse.down();
  await page.mouse.move(initial!.x+initial!.width,centerY,{steps:5});
  await page.mouse.up();
  await expect(page.locator('.assembly-clip-instances .assembly-clip-entry small')).toContainText('1.00–3.00 s');
  const moved=await placement.boundingBox();expect(moved).toBeTruthy();
  await page.mouse.move(moved!.x+moved!.width-3,centerY);
  await page.mouse.down();
  await page.mouse.move(moved!.x+moved!.width-3+moved!.width/2,centerY,{steps:5});
  await page.mouse.up();
  await expect(page.locator('.assembly-clip-instances .assembly-clip-entry small')).toContainText('1.00–4.00 s');
  const downloaded=page.waitForEvent('download');
  await page.getByRole('button',{name:'File',exact:true}).click();
  await page.getByRole('button',{name:'Download project copy'}).click();
  await page.locator('input[type=file][accept=".hyde,.hy"]').setInputFiles((await (await downloaded).path())!);
  await page.locator('.layer-name').filter({hasText:'New assembly'}).click();
  await expect(page.getByRole('button',{name:'Place Turn and reveal clip'})).toBeVisible();
  await expect(page.locator('.assembly-instance-block')).toContainText('Turn and reveal');
  await expect(page.locator('.assembly-clip-instances .assembly-clip-entry small')).toContainText('1.00–4.00 s');
});
