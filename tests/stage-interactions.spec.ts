  const before=await page.locator('.stage-frame').boundingBox();
  await page.locator('.stage-workspace').hover({position:{x:10,y:10}});
  await page.mouse.down();await page.mouse.move(70,70,{steps:4});await page.mouse.up();
  const after=await page.locator('.stage-frame').boundingBox();expect(after!.x).not.toBeCloseTo(before!.x,0);
  await page.getByRole('button',{name:'Home stage',exact:true}).click();
  const home=await page.locator('.stage-frame').boundingBox();expect(home!.x).toBeCloseTo(before!.x,0);
  await page.locator('.stage-frame').hover();await page.mouse.wheel(0,-200);
