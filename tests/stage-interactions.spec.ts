  await page.getByRole('button',{name:'Show stage grid',exact:true}).click();
  await page.getByRole('spinbutton',{name:'Grid divisions',exact:true}).fill('5');
  await expect(page.locator('.stage-guides line')).toHaveCount(8);
  const stage=await page.locator('.stage-frame').boundingBox();expect(stage).toBeTruthy();
  const point=(x:number,y:number)=>({x:stage!.x+x/1920*stage!.width,y:stage!.y+y/1080*stage!.height});
  const a=point(500,350),b=point(1100,730);
  await page.mouse.move(a.x,a.y);await page.mouse.down();await page.mouse.move(b.x,b.y,{steps:7});await page.mouse.up();
