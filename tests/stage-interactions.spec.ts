import {test,expect} from '@playwright/test';

test('stage, artwork and handles stay aligned across window and project sizes',async({page})=>{
  await page.setViewportSize({width:1920,height:1050});
  await page.goto('/');await page.getByRole('button',{name:/New project Choose a size/}).click();await page.getByRole('button',{name:'Done',exact:true}).click();
  await page.getByRole('button',{name:'Add rectangle',exact:true}).click();
  const frame=page.locator('.stage-frame'),overlay=page.locator('.selection-overlay'),canvas=page.locator('.stage-frame canvas');
  const dimensions=async()=>({frame:await frame.boundingBox(),overlay:await overlay.boundingBox()});
  let boxes=await dimensions();expect(boxes.frame).toBeTruthy();expect(boxes.overlay).toBeTruthy();
  expect(boxes.frame!.width/boxes.frame!.height).toBeCloseTo(960/540,2);
  expect(boxes.overlay!.width).toBeCloseTo(boxes.frame!.width,0);
  expect(boxes.overlay!.height).toBeCloseTo(boxes.frame!.height,0);
  const pivot=page.locator('.selection-overlay .pivot');
  const pivotBox=await pivot.boundingBox();expect(pivotBox).toBeTruthy();
  await page.mouse.move(pivotBox!.x+30,pivotBox!.y+30);await page.mouse.down();await page.mouse.move(pivotBox!.x+110,pivotBox!.y+80,{steps:8});await page.mouse.up();
  const x=Number(await page.getByRole('spinbutton',{name:'X',exact:true}).inputValue());
  const y=Number(await page.getByRole('spinbutton',{name:'Y',exact:true}).inputValue());
  expect(x).toBeGreaterThan(960);expect(y).toBeGreaterThan(540);
  await expect.poll(()=>canvas.evaluate((c:HTMLCanvasElement,[px,py])=>{const probe=document.createElement('canvas');probe.width=c.width;probe.height=c.height;const ctx=probe.getContext('2d')!;ctx.drawImage(c,0,0);const d=ctx.getImageData(Math.round(px+240),Math.round(py+240),1,1).data;return d[0]>210&&d[1]>150&&d[2]<130;},[x,y] as const)).toBeTruthy();
  await page.locator('.stage-toolbar').getByRole('button',{name:'1920 × 1080',exact:true}).click();
  await page.locator('.dialog').getByRole('spinbutton',{name:'Width',exact:true}).fill('720');
  await page.locator('.dialog').getByRole('spinbutton',{name:'Height',exact:true}).fill('720');
  await page.getByRole('button',{name:'Done',exact:true}).click();
  boxes=await dimensions();expect(boxes.frame!.width/boxes.frame!.height).toBeCloseTo(1,2);
  expect(boxes.overlay!.width).toBeCloseTo(boxes.frame!.width,0);
  await expect(page.getByRole('spinbutton',{name:'X',exact:true})).toHaveValue(String(x));
  await page.setViewportSize({width:1280,height:900});
  boxes=await dimensions();expect(boxes.frame!.width/boxes.frame!.height).toBeCloseTo(1,2);
  expect(boxes.overlay!.height).toBeCloseTo(boxes.frame!.height,0);
});

test('pivot reset preserves artwork and off-frame art remains visible',async({page})=>{
  await page.goto('/');await page.getByRole('button',{name:/New project Choose a size/}).click();await page.getByRole('button',{name:'Done',exact:true}).click();
  await page.getByRole('button',{name:'Add rectangle',exact:true}).click();
  const canvas=page.locator('.stage-frame canvas');
  const image=()=>canvas.evaluate((c:HTMLCanvasElement)=>c.toDataURL());
  const before=await image();
  await page.getByRole('button',{name:'Edit pivot (keeps artwork stationary)',exact:true}).click();
  const box=await page.getByLabel('Move pivot',{exact:true}).boundingBox();expect(box).toBeTruthy();
  await page.mouse.move(box!.x+box!.width/2,box!.y+box!.height/2);await page.mouse.down();await page.mouse.move(box!.x+box!.width/2+40,box!.y+box!.height/2+25,{steps:6});await page.mouse.up();
  await expect.poll(image).toEqual(before);
  await page.getByRole('button',{name:'Reset pivot to center',exact:true}).click();
  await expect.poll(image).toEqual(before);
  await page.getByRole('spinbutton',{name:'X',exact:true}).fill('-80');
  await expect.poll(()=>canvas.evaluate((c:HTMLCanvasElement)=>{const p=document.createElement('canvas');p.width=c.width;p.height=c.height;const ctx=p.getContext('2d')!;ctx.drawImage(c,0,0);const d=ctx.getImageData(160,780,1,1).data;return d[0]>210&&d[1]>150&&d[2]<130;})).toBeTruthy();
});

