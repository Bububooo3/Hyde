import {expect,test} from '@playwright/test';

test('assembly clip gaps can be selected and edited per property, then reopened',async({page})=>{
  await page.goto('/');
  await page.getByRole('button',{name:'New project'}).click();
  await page.getByRole('button',{name:'Done'}).click();
  await page.getByRole('button',{name:'Add rectangle'}).first().click();
  await page.keyboard.press('Control+g');
  await page.getByRole('textbox',{name:'Assembly clip name'}).fill('Pose');
  await page.getByRole('spinbutton',{name:'Assembly clip length in seconds'}).fill('2');
  await page.getByRole('button',{name:'Save animation clip'}).click();
  await page.getByRole('button',{name:'Place Pose clip'}).click();
  const ruler=page.getByLabel('Timeline ruler'),box=await ruler.boundingBox();
  expect(box).toBeTruthy();
  await ruler.click({position:{x:box!.width*.5,y:10}});
  await page.getByRole('button',{name:'Place Pose clip'}).click();
  const band=page.getByRole('button',{name:/Tween transition from 2\.00 to \d+\.\d+ seconds/});
  await expect(band).toBeVisible();
  await band.click();
  await page.getByRole('button',{name:'Edit assembly animation…'}).click();
  const mode=page.getByRole('combobox',{name:/Position X transition mode/}).first();
  await expect(mode).toHaveValue('tween');
  await mode.selectOption('hold');
  await expect(mode).toHaveValue('hold');
  await page.getByRole('dialog',{name:'Edit assembly animation'}).getByRole('button',{name:'Apply'}).click();
  await expect(page.getByRole('button',{name:/Mixed transition from 2\.00 to \d+\.\d+ seconds/})).toBeVisible();
  await page.getByRole('button',{name:'Edit assembly animation…'}).click();
  await page.getByRole('button',{name:/Reset .* Position X transition/}).first().click();
  await expect(mode).toHaveValue('tween');
  await mode.selectOption('hold');
  await page.getByRole('dialog',{name:'Edit assembly animation'}).getByRole('button',{name:'Apply'}).click();
  const downloaded=page.waitForEvent('download');
  await page.getByRole('button',{name:'File',exact:true}).click();
  await page.getByRole('button',{name:'Download project copy'}).click();
  await page.locator('input[type=file][accept=".hyde,.hy"]').setInputFiles((await (await downloaded).path())!);
  await page.locator('.layer-name').filter({hasText:'New assembly'}).click();
  await page.getByRole('button',{name:'Edit assembly animation…'}).click();
  await expect(page.getByRole('combobox',{name:/Position X transition mode/}).first()).toHaveValue('hold');
});

