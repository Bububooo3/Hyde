test('shared assembly keys update placements while a local key stays independent',async({page})=>{
  await page.goto('/');
  await page.getByRole('button',{name:'New project'}).click();
  await page.getByRole('button',{name:'Done'}).click();
  await page.getByRole('button',{name:'Add rectangle'}).first().click();
  await page.keyboard.press('Control+g');
  await page.getByRole('spinbutton',{name:'Assembly clip length in seconds'}).fill('2');
  await page.getByRole('button',{name:'Save animation clip'}).click();
  await page.getByRole('button',{name:'Place Animation clip clip'}).click();
  const ruler=page.getByLabel('Timeline ruler'),box=await ruler.boundingBox();
  expect(box).toBeTruthy();
  await ruler.click({position:{x:box!.width*.5,y:10}});
  await page.getByRole('button',{name:'Place Animation clip clip'}).click();
  await page.getByRole('button',{name:'Edit assembly animation…'}).click();
  const editor=page.getByRole('region',{name:'Assembly clip keys'});
  await expect(editor).toBeVisible();
  await editor.getByRole('combobox',{name:'Assembly clip track'}).selectOption({label:'Rectangle · Position X'});
  await editor.getByRole('button',{name:'Shared source'}).click();
  const value=editor.getByRole('spinbutton',{name:'Assembly key 1 value'});
  await value.fill('80');await value.press('Enter');
  await expect(value).toHaveValue('80');
  await editor.getByRole('combobox',{name:'Placed clip to edit'}).selectOption({index:1});
  await expect(value).toHaveValue('80');
  await editor.getByRole('button',{name:'This placement'}).click();
  await value.fill('120');await value.press('Enter');
  await expect(value).toHaveValue('120');
  await editor.getByRole('combobox',{name:'Placed clip to edit'}).selectOption({index:0});
  await expect(value).toHaveValue('80');
  await editor.getByRole('combobox',{name:'Placed clip to edit'}).selectOption({index:1});
  await expect(value).toHaveValue('120');
  await page.getByRole('dialog',{name:'Edit assembly animation'}).getByRole('button',{name:'Apply'}).click();
  await page.getByRole('button',{name:'Show assembly master'}).click();
  const localMasterKey=page.getByRole('button',{name:/Rectangle Position X local key at/}).first();
  await expect(localMasterKey).toBeVisible();
  await localMasterKey.click();
  await page.getByRole('button',{name:'Edit assembly animation…'}).click();
  await expect(editor.getByRole('button',{name:'This placement'})).toHaveAttribute('aria-pressed','true');
  await expect(editor.getByRole('combobox',{name:'Assembly clip track'}).locator('option:checked')).toHaveText('Rectangle · Position X');
  await page.getByRole('dialog',{name:'Edit assembly animation'}).getByRole('button',{name:'Cancel'}).click();
  await expect(page.locator('.assembly-master-curve').first()).toBeVisible();
  const keyBox=await localMasterKey.boundingBox();expect(keyBox).toBeTruthy();
  await page.mouse.move(keyBox!.x+keyBox!.width/2,keyBox!.y+keyBox!.height/2);
  await page.mouse.down();
  await page.mouse.move(keyBox!.x+keyBox!.width/2+50,keyBox!.y+keyBox!.height/2,{steps:6});
  await page.mouse.up();
  await page.getByRole('button',{name:'Edit assembly animation…'}).click();
  await expect.poll(async()=>Number(await editor.getByRole('spinbutton',{name:'Assembly key 1 time'}).inputValue())).toBeGreaterThan(.2);
  await page.getByRole('dialog',{name:'Edit assembly animation'}).getByRole('button',{name:'Cancel'}).click();
  await page.getByRole('button',{name:'Undo (Ctrl Z)'}).click();
  await page.getByRole('button',{name:'Edit assembly animation…'}).click();
  await expect(editor.getByRole('spinbutton',{name:'Assembly key 1 time'})).toHaveValue('0');
  await page.getByRole('dialog',{name:'Edit assembly animation'}).getByRole('button',{name:'Cancel'}).click();
  await page.getByRole('button',{name:'Redo'}).click();
  await page.getByRole('button',{name:'Edit assembly animation…'}).click();
  await expect.poll(async()=>Number(await editor.getByRole('spinbutton',{name:'Assembly key 1 time'}).inputValue())).toBeGreaterThan(.2);
  await page.getByRole('dialog',{name:'Edit assembly animation'}).getByRole('button',{name:'Cancel'}).click();
  const downloaded=page.waitForEvent('download');
  await page.getByRole('button',{name:'File',exact:true}).click();
  await page.getByRole('button',{name:'Download project copy'}).click();
  await page.locator('input[type=file][accept=".hyde,.hy"]').setInputFiles((await (await downloaded).path())!);
  await page.locator('.layer-name').filter({hasText:'New assembly'}).click();
  await page.getByRole('button',{name:'Edit assembly animation…'}).click();
  await expect(page.getByRole('region',{name:'Assembly clip keys'}).getByRole('spinbutton',{name:'Assembly key 1 value'})).toHaveValue('120');
  await expect.poll(async()=>Number(await page.getByRole('region',{name:'Assembly clip keys'}).getByRole('spinbutton',{name:'Assembly key 1 time'}).inputValue())).toBeGreaterThan(.2);
});
