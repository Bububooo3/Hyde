import { expect, test } from '@playwright/test';
import { readFile } from 'node:fs/promises';
import { strFromU8, unzipSync } from 'fflate';

test('Negate creates an editable hole, keeps hidden sources, and exports the native path', async ({ page }) => {
  await page.goto('/');
  await page.getByRole('button', { name: 'New project' }).click();
  await page.getByRole('button', { name: 'Done', exact: true }).click();
  await page.getByRole('button', { name: 'Add rectangle' }).first().click();
  await page.getByLabel('Element name').fill('Outer');
  await page.getByRole('button', { name: 'Add rectangle' }).first().click();
  await page.getByLabel('Element name').fill('Inner');
  await page.getByRole('spinbutton', { name: 'Width', exact: true }).fill('80');
  await page.getByRole('spinbutton', { name: 'Height', exact: true }).fill('80');
  const rows = page.locator('.scene-element-row');
  await rows.filter({ hasText: 'Outer' }).click();
  await rows.filter({ hasText: 'Inner' }).click({ modifiers: ['Control'] });
  await page.getByRole('button', { name: 'Negate', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Edit path on stage' })).toBeVisible();
  await expect(rows).toHaveCount(3);
  await expect(rows.filter({ has: page.getByRole('button', { name: 'Select Outer', exact: true }) })).toHaveClass(/dimmed/);
  await expect(rows.filter({ has: page.getByRole('button', { name: 'Select Inner', exact: true }) })).toHaveClass(/dimmed/);
  await page.keyboard.press('Control+z');
  await expect(rows).toHaveCount(2);
  await page.keyboard.press('Control+y');
  await expect(rows).toHaveCount(3);
  const projectDownload = page.waitForEvent('download');
  await page.getByRole('button', { name: 'File', exact: true }).click();
  await page.getByRole('button', { name: 'Download project copy' }).click();
  await page.locator('input[type=file][accept=".hyde,.hy"]').setInputFiles((await (await projectDownload).path())!);
  await expect(rows).toHaveCount(3);
  await page.getByRole('button', { name: 'Export', exact: true }).click();
  const webDownload = page.waitForEvent('download');
  await page.getByRole('button', { name: /Standalone web story/ }).click();
  const zip = unzipSync(new Uint8Array(await readFile((await (await webDownload).path())!)));
  const story = JSON.parse(strFromU8(zip['story.json']));
  const result = story.elements.find((element: { name: string }) => element.name.startsWith('Negate'));
  expect(result.shapePath.holes).toHaveLength(1);
  expect(story.elements.filter((element: { hidden?: boolean }) => element.hidden)).toHaveLength(2);
});
