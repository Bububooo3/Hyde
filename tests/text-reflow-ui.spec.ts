import {expect,test} from '@playwright/test';
import {readFile} from 'node:fs/promises';
import {unzipSync} from 'fflate';

test('animated reflow follows a keyed shape and survives project and web export',async({page})=>{
  test.setTimeout(90_000);
  await page.goto('/');
  await page.getByRole('button',{name:'New project'}).click();
  await page.getByRole('button',{name:'Done'}).click();
  await page.getByRole('button',{name:'Add rectangle'}).click();
  await page.getByRole('spinbutton',{name:'Width',exact:true}).fill('160');
  await page.getByRole('button',{name:'Keyframe position'}).click();
  await page.getByRole('button',{name:'Auto key'}).click();
  const seek=async(seconds:number)=>{
    const marker=page.locator('.ruler > span').filter({hasText:`${seconds}s`}).first();
    const box=await marker.boundingBox();expect(box).toBeTruthy();
    await page.mouse.click(box!.x+box!.width/2,box!.y+box!.height/2);
  };
  await seek(2);
  await page.getByRole('spinbutton',{name:'X',exact:true}).fill('1230');
  await page.getByRole('button',{name:'Auto key'}).click();
  await page.getByRole('button',{name:'Back to start'}).click();
  await page.getByRole('button',{name:'Add text'}).click();
  await page.getByRole('textbox',{name:'Text content'}).fill('Stable words flow around an animated shape and arrive together at a new arrangement.');
  await page.getByRole('spinbutton',{name:'Width',exact:true}).fill('450');
  await page.getByRole('spinbutton',{name:'Height',exact:true}).fill('260');
  await page.getByRole('spinbutton',{name:'Font size'}).fill('30');
  await page.getByRole('combobox',{name:'Text shape target'}).selectOption({label:'Rectangle'});
  await seek(1);
  const frame=()=>page.locator('.stage-frame canvas').evaluate((canvas:HTMLCanvasElement)=>canvas.toDataURL());
  await expect.poll(async()=>{const a=await frame();await page.waitForTimeout(70);return a===await frame();}).toBe(true);
  const live=await frame();
  await page.getByRole('checkbox',{name:'Animate text reflow'}).check();
  await page.getByRole('spinbutton',{name:'Text reflow start'}).fill('0');
  await page.getByRole('spinbutton',{name:'Text reflow duration'}).fill('2');
  await expect.poll(frame).not.toBe(live);
  const glide=await frame();
  await page.getByRole('combobox',{name:'Text reflow preset'}).selectOption('cascade');
  await expect.poll(frame).not.toBe(glide);
  const cascade=await frame();
  const download=page.waitForEvent('download');
  await page.getByRole('button',{name:'File',exact:true}).click();
  await page.getByRole('button',{name:'Download project copy'}).click();
  await page.locator('input[type=file][accept=".hyde,.hy"]').setInputFiles((await (await download).path())!);
  await page.locator('.layer-name').filter({hasText:'Text'}).click();
  await expect(page.getByRole('combobox',{name:'Text reflow preset'})).toHaveValue('cascade');
  await seek(1);
  await expect.poll(frame).toBe(cascade);
  await page.getByRole('button',{name:'Export',exact:true}).click();
  const webDownload=page.waitForEvent('download');
  await page.getByRole('button',{name:/Standalone web story/}).click();
  const zip=unzipSync(new Uint8Array(await readFile((await (await webDownload).path())!)));
  expect(new TextDecoder().decode(zip['index.html'])).toContain('textReflow');
});
