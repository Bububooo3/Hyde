import {expect,test} from '@playwright/test';

test('static shape-aware text keeps its arrangement until refreshed and survives reopening',async({page})=>{
  test.setTimeout(90_000);
  await page.goto('/');
  await page.getByRole('button',{name:'New project'}).click();
  await page.getByRole('button',{name:'Done'}).click();
  await page.getByRole('button',{name:'Add rectangle'}).click();
  await page.getByRole('spinbutton',{name:'Width',exact:true}).fill('160');
  await page.getByRole('button',{name:'Add text'}).click();
  await page.getByRole('textbox',{name:'Text content'}).fill('The words bend around this shape. The arrangement stays in place until the author asks for a refresh.');
  await page.getByRole('spinbutton',{name:'Width',exact:true}).fill('470');
  await page.getByRole('spinbutton',{name:'Height',exact:true}).fill('260');
  await page.getByRole('spinbutton',{name:'Font size'}).fill('30');
  await page.getByRole('combobox',{name:'Text shape target'}).selectOption({label:'Rectangle'});
  await page.getByRole('combobox',{name:'Text layout'}).selectOption('static');
  await expect(page.getByText(/Layout captured at/)).toBeVisible();
  const canvas=page.locator('.stage-frame canvas');
  const frame=()=>canvas.evaluate((element:HTMLCanvasElement)=>element.toDataURL());
  await page.getByRole('button',{name:'Hide Rectangle'}).click();
  await expect.poll(async()=>{const first=await frame();await page.waitForTimeout(80);return first===await frame();}).toBe(true);
  const original=await frame();
  await page.locator('.layer-name').filter({hasText:'Rectangle'}).click();
  await page.getByRole('spinbutton',{name:'X',exact:true}).fill('1150');
  await page.waitForTimeout(200);
  expect(await frame()).toBe(original);
  await page.getByRole('button',{name:'Show Rectangle'}).click();
  await page.locator('.layer-name').filter({hasText:'Text'}).click();
  await page.getByRole('button',{name:'Refresh static layout at playhead'}).click();
  await page.getByRole('button',{name:'Hide Rectangle'}).click();
  await expect.poll(frame).not.toBe(original);
  const refreshed=await frame();
  const download=page.waitForEvent('download');
  await page.getByRole('button',{name:'File',exact:true}).click();
  await page.getByRole('button',{name:'Download project copy'}).click();
  const path=await (await download).path();expect(path).toBeTruthy();
  await page.locator('input[type=file][accept=".hyde,.hy"]').setInputFiles(path!);
  await expect.poll(frame).toBe(refreshed);
});
